using ZongziTEK.BlackboardSticker.Models;

static void Check(bool pass, string message) { if (!pass) throw new Exception(message); Console.WriteLine("PASS " + message); }
var profile = new ScheduleProfile();
var math = new SubjectEntry { Name = "数学" }; profile.Subjects.Add(math);
var lesson = new TimeSlot { Start = TimeSpan.FromHours(8), End = TimeSpan.FromMinutes(520) };
profile.DefaultSlots.Add(lesson);
profile.Day(DayOfWeek.Monday).Subjects[lesson.Id] = math.Id;
var date = new DateTime(2026, 11, 2);
ReminderState At(string time) => ReminderEngine.Evaluate(profile, date + TimeSpan.Parse(time));
Check(At("07:57:29") == null, "not before lead interval");
Check(At("07:57:30")?.BeforeClass == true, "starts 30 seconds before preparation bell");
Check(At("07:58:00")?.Key == At("07:57:30")?.Key, "same reminder across bell");
Check(At("08:00:00") == null, "hides at formal start");
Check(At("08:39:59") == null, "no premature dismissal");
Check(At("08:40:00")?.BeforeClass == false, "dismissal at exact end");
Check(At("08:40:59") != null && At("08:41:00") == null, "dismissal lasts 60 seconds");
profile.DismissalSeconds = 90;
Check(At("08:41:29") != null && At("08:41:30") == null, "custom dismissal length");
profile.ReminderLeadSeconds = 45;
Check(At("07:57:15") != null && At("07:57:14") == null, "custom preparation lead");
var exercise = new TimeSlot { Start = TimeSpan.Parse("07:55"), End = lesson.Start, IsExercise = true };
profile.DefaultSlots.Insert(0, exercise);
Check(At("07:55:00")?.Title.Contains("眼保健操") == true, "exercise starts early reminder with subject");
Check(At("07:55:00")?.Key == At("07:59:00")?.Key, "exercise and preparation use one key");
Check(At("07:56:23") != null, "restores current interval after missed seconds");
profile.Day(DayOfWeek.Tuesday).Subjects[lesson.Id] = math.Id;
var exception = profile.Compose(date.AddDays(1), DayOfWeek.Monday, DayOfWeek.Monday, out var surplus); profile.Exceptions.Add(exception);
Check(profile.Lessons(date.AddDays(1)).Last().Subject == "数学", "date override resolves composed subjects");
math.Name = "数学 A";
Check(profile.Lessons(date.AddDays(1)).Last().Subject == "数学 A", "rename updates references");
Check(profile.Day(DayOfWeek.Monday).Slots == null, "composition does not modify source timetable");
var independent = ScheduleProfile.Clone(profile.DefaultSlots); independent.Last().Start = TimeSpan.FromHours(9); independent.Last().End = TimeSpan.FromHours(10);
profile.Day(DayOfWeek.Wednesday).Slots = independent;
Check(profile.Slots(DayOfWeek.Monday).Last().Start == TimeSpan.FromHours(8), "independent day retains default for others");
var previous = new Timetable(); previous.Monday.Add(new Lesson("语文", TimeSpan.FromHours(8), TimeSpan.FromHours(9), false, false)); previous.Tuesday.Add(new Lesson("英语", TimeSpan.FromHours(10), TimeSpan.FromHours(11), false, false));
var migrated = ScheduleProfile.Migrate(previous);
Check(migrated.Lessons(date).Single().Subject == "语文" && migrated.Lessons(date.AddDays(1)).Single().StartTime == TimeSpan.FromHours(10), "migration preserves differing days");
profile.Validate();
Console.WriteLine("All schedule boundary tests passed.");
